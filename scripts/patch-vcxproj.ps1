<#
.SYNOPSIS
Idempotently apply Nottawa's required MSVC project settings to a .vcxproj
freshly generated by OpenFrameworks projectGenerator.

.DESCRIPTION
projectGenerator produces a serviceable .vcxproj but omits Nottawa-specific
include paths, preprocessor defines, subsystem choice, .mm/.m exclusion,
and the Windows _win.cpp stub inclusion. This script edits the .vcxproj in
place. Safe to re-run after every projectGenerator invocation.

.PARAMETER Project
Path to the .vcxproj to patch. Default: apps/myApps/Nottawa/Nottawa.vcxproj
relative to repo root.

.PARAMETER RepoRoot
Repo root (directory that contains src/). Default: two levels up from this script.

.EXAMPLE
pwsh scripts\patch-vcxproj.ps1
pwsh scripts\patch-vcxproj.ps1 -Project C:\path\to\Nottawa.vcxproj
#>

[CmdletBinding()]
param(
    [string]$Project,
    [string]$RepoRoot
)

$ErrorActionPreference = 'Stop'

if (-not $RepoRoot) {
    $RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
}
if (-not $Project) {
    $Project = Join-Path $RepoRoot 'apps\myApps\Nottawa\Nottawa.vcxproj'
}

if (-not (Test-Path $Project)) {
    throw "vcxproj not found at $Project. Run OF projectGenerator first."
}

Write-Host "Patching $Project" -ForegroundColor Cyan

# --- Config we want present on every ItemDefinitionGroup -----------------

$RequiredDefines = @(
    'NOMINMAX',
    'WIN32_LEAN_AND_MEAN',
    '_USE_MATH_DEFINES',
    '__WINDOWS_WASAPI__',
    'TARGET_WIN32',
    'GLM_FORCE_CTOR_INIT',
    'GLM_ENABLE_EXPERIMENTAL',
    'OF_NO_FMOD=1',
    'USE_KISS_FFT',
    'ofxAddons_ENABLE_IMGUI',
    'JSON_DIAGNOSTICS=1',
    'IMGUI_DEFINE_MATH_OPERATORS=1'
)

# All src/** directories (recursive) and select lib/** dirs get include paths.
$SrcRoot = Join-Path $RepoRoot 'src'
$LibRoot = Join-Path $RepoRoot 'lib'
$IncludeDirs = @()
if (Test-Path $SrcRoot) {
    $IncludeDirs += Get-ChildItem -Path $SrcRoot -Directory -Recurse |
        ForEach-Object { $_.FullName }
    $IncludeDirs = @($SrcRoot) + $IncludeDirs
}
if (Test-Path $LibRoot) {
    $IncludeDirs += Get-ChildItem -Path $LibRoot -Directory |
        ForEach-Object { $_.FullName }
}
# Normalize to project-relative $(ProjectDir)-anchored paths for portability.
$ProjectDir = Split-Path -Parent $Project
$IncludeDirs = $IncludeDirs | ForEach-Object {
    # Fall back to absolute path if Resolve-Path -Relative isn't supported
    Push-Location $ProjectDir
    try { (Resolve-Path -LiteralPath $_ -Relative -ErrorAction Stop) }
    catch { $_ }
    finally { Pop-Location }
}

# ObjC++ files that must NOT compile on Windows even though projectGenerator
# may enumerate them. Belt-and-braces beyond the __APPLE__ gate.
$ExcludeMasks = @(
    '*.mm',
    '*.m',
    'src\Bridge\*',
    'src\Engine\NottawaApp*',
    'src\Engine\*.mm'
)

# Windows _win.cpp stubs that must be in the project even if projectGenerator
# skips them (some versions filter by filename pattern).
$RequiredCompileItems = @(
    'src\Audio\SystemAudioSource_win.cpp',
    'src\Video\Recording\AVFRecorderWrapper_win.cpp',
    'src\Engine\IOSurfaceTextureManager_win.cpp',
    'src\Services\SparkleUpdater_win.cpp',
    'src\Services\URLSchemeHandler_win.cpp',
    'src\Services\BookmarkService_win.cpp',
    'src\Video\OutputWindow_win.cpp',
    'src\Util\PortabilityCheck.cpp',
    'src\Util\Utf8Path.cpp',
    'src\Util\ComApartment.hpp'
)

# --- Load XML -----------------------------------------------------------

[xml]$xml = Get-Content -LiteralPath $Project
$ns = New-Object System.Xml.XmlNamespaceManager($xml.NameTable)
$ns.AddNamespace('m', 'http://schemas.microsoft.com/developer/msbuild/2003')

function Ensure-DefinesAndFlags {
    param($xml, $ns, $defines, $includeDirs)

    $idgs = $xml.SelectNodes('//m:ItemDefinitionGroup', $ns)
    foreach ($idg in $idgs) {
        # ClCompile
        $cl = $idg.SelectSingleNode('m:ClCompile', $ns)
        if (-not $cl) {
            $cl = $xml.CreateElement('ClCompile', $ns.LookupNamespace('m'))
            [void]$idg.AppendChild($cl)
        }

        # PreprocessorDefinitions
        $pp = $cl.SelectSingleNode('m:PreprocessorDefinitions', $ns)
        $existing = if ($pp) { $pp.InnerText } else { '%(PreprocessorDefinitions)' }
        $existingList = $existing.Split(';') | Where-Object { $_ -ne '' }
        $merged = $existingList
        foreach ($d in $defines) {
            if ($merged -notcontains $d) { $merged += $d }
        }
        if ($merged -notcontains '%(PreprocessorDefinitions)') {
            $merged += '%(PreprocessorDefinitions)'
        }
        if (-not $pp) {
            $pp = $xml.CreateElement('PreprocessorDefinitions', $ns.LookupNamespace('m'))
            [void]$cl.AppendChild($pp)
        }
        $pp.InnerText = ($merged -join ';')

        # AdditionalIncludeDirectories
        $inc = $cl.SelectSingleNode('m:AdditionalIncludeDirectories', $ns)
        $existingInc = if ($inc) { $inc.InnerText } else { '%(AdditionalIncludeDirectories)' }
        $existingIncList = $existingInc.Split(';') | Where-Object { $_ -ne '' }
        $mergedInc = $existingIncList
        foreach ($d in $includeDirs) {
            if ($mergedInc -notcontains $d) { $mergedInc += $d }
        }
        if ($mergedInc -notcontains '%(AdditionalIncludeDirectories)') {
            $mergedInc += '%(AdditionalIncludeDirectories)'
        }
        if (-not $inc) {
            $inc = $xml.CreateElement('AdditionalIncludeDirectories', $ns.LookupNamespace('m'))
            [void]$cl.AppendChild($inc)
        }
        $inc.InnerText = ($mergedInc -join ';')

        # LanguageStandard = /std:c++17
        $ls = $cl.SelectSingleNode('m:LanguageStandard', $ns)
        if (-not $ls) {
            $ls = $xml.CreateElement('LanguageStandard', $ns.LookupNamespace('m'))
            [void]$cl.AppendChild($ls)
        }
        $ls.InnerText = 'stdcpp17'

        # Conformance mode (permissive- helps NOMINMAX and std correctness)
        $cm = $cl.SelectSingleNode('m:ConformanceMode', $ns)
        if (-not $cm) {
            $cm = $xml.CreateElement('ConformanceMode', $ns.LookupNamespace('m'))
            [void]$cl.AppendChild($cm)
        }
        $cm.InnerText = 'true'

        # Link > SubSystem = Windows
        $link = $idg.SelectSingleNode('m:Link', $ns)
        if (-not $link) {
            $link = $xml.CreateElement('Link', $ns.LookupNamespace('m'))
            [void]$idg.AppendChild($link)
        }
        $ss = $link.SelectSingleNode('m:SubSystem', $ns)
        if (-not $ss) {
            $ss = $xml.CreateElement('SubSystem', $ns.LookupNamespace('m'))
            [void]$link.AppendChild($ss)
        }
        $ss.InnerText = 'Windows'

        # If OF's main.cpp is plain `int main` (not WinMain), we need this
        # entry point override so SubSystem=Windows still finds the entry.
        $ep = $link.SelectSingleNode('m:EntryPointSymbol', $ns)
        if (-not $ep) {
            $ep = $xml.CreateElement('EntryPointSymbol', $ns.LookupNamespace('m'))
            [void]$link.AppendChild($ep)
        }
        # Leave empty by default; only set if you confirm OF ships plain `main`.
        if (-not $ep.InnerText) { $ep.InnerText = 'mainCRTStartup' }
    }
}

function Ensure-ExcludeFromBuild {
    param($xml, $ns, $masks)

    # Find every ClCompile with Include matching an ObjC++ mask; add
    # ExcludedFromBuild=true if not already present.
    $items = $xml.SelectNodes('//m:ItemGroup/m:ClCompile', $ns)
    foreach ($it in $items) {
        $inc = $it.GetAttribute('Include')
        if (-not $inc) { continue }
        $matched = $false
        foreach ($m in $masks) {
            if ($inc -like $m) { $matched = $true; break }
        }
        if (-not $matched) { continue }

        $ex = $it.SelectSingleNode('m:ExcludedFromBuild', $ns)
        if (-not $ex) {
            $ex = $xml.CreateElement('ExcludedFromBuild', $ns.LookupNamespace('m'))
            [void]$it.AppendChild($ex)
        }
        $ex.InnerText = 'true'
    }
}

function Ensure-CompileItems {
    param($xml, $ns, $items)

    # Grab or create an ItemGroup for our added items so we can find them
    # on re-runs by Label.
    $group = $xml.SelectSingleNode("//m:ItemGroup[@Label='NottawaWinStubs']", $ns)
    if (-not $group) {
        $group = $xml.CreateElement('ItemGroup', $ns.LookupNamespace('m'))
        $group.SetAttribute('Label', 'NottawaWinStubs')
        [void]$xml.DocumentElement.AppendChild($group)
    }

    foreach ($p in $items) {
        # Skip if any ClCompile / ClInclude already lists this file.
        $existing = $xml.SelectNodes("//m:ClCompile[@Include=`"$p`"] | //m:ClInclude[@Include=`"$p`"]", $ns)
        if ($existing.Count -gt 0) { continue }

        # .hpp go in ClInclude, .cpp in ClCompile.
        $tag = if ($p -like '*.hpp' -or $p -like '*.h') { 'ClInclude' } else { 'ClCompile' }
        $node = $xml.CreateElement($tag, $ns.LookupNamespace('m'))
        $node.SetAttribute('Include', $p)
        [void]$group.AppendChild($node)
    }
}

function Ensure-DataRobocopy {
    param($xml, $ns, $repoRoot)

    # Post-build event: robocopy repo data/ to $(OutDir)data\.
    # Robocopy exit codes 0-7 are success; wrap so MSBuild doesn't treat 1 as failure.
    $cmd = @"
if not exist "`$(OutDir)data" mkdir "`$(OutDir)data"
robocopy "`$(SolutionDir)..\..\..\data" "`$(OutDir)data" /MIR /NFL /NDL /NJH /NJS /NC /NS /NP
if %ERRORLEVEL% GEQ 8 exit /b 1
exit /b 0
"@

    $idgs = $xml.SelectNodes('//m:ItemDefinitionGroup', $ns)
    foreach ($idg in $idgs) {
        $pb = $idg.SelectSingleNode('m:PostBuildEvent', $ns)
        if (-not $pb) {
            $pb = $xml.CreateElement('PostBuildEvent', $ns.LookupNamespace('m'))
            [void]$idg.AppendChild($pb)
        }
        $cmdNode = $pb.SelectSingleNode('m:Command', $ns)
        if (-not $cmdNode) {
            $cmdNode = $xml.CreateElement('Command', $ns.LookupNamespace('m'))
            [void]$pb.AppendChild($cmdNode)
        }
        # Only overwrite if we haven't already stamped our command in.
        if ($cmdNode.InnerText -notlike '*robocopy*data*') {
            $cmdNode.InnerText = $cmd
        }
    }
}

Ensure-DefinesAndFlags -xml $xml -ns $ns -defines $RequiredDefines -includeDirs $IncludeDirs
Ensure-ExcludeFromBuild -xml $xml -ns $ns -masks $ExcludeMasks
Ensure-CompileItems -xml $xml -ns $ns -items $RequiredCompileItems
Ensure-DataRobocopy -xml $xml -ns $ns -repoRoot $RepoRoot

# Preserve encoding and formatting on save
$settings = New-Object System.Xml.XmlWriterSettings
$settings.Indent = $true
$settings.IndentChars = '  '
$settings.NewLineChars = "`r`n"
$settings.Encoding = [System.Text.Encoding]::UTF8
$writer = [System.Xml.XmlWriter]::Create($Project, $settings)
try { $xml.Save($writer) } finally { $writer.Dispose() }

Write-Host "Patched: defines added, includes added, subsystem=Windows," -ForegroundColor Green
Write-Host "         .mm/.m excluded, _win.cpp stubs included, data/ robocopy step added." -ForegroundColor Green
Write-Host "Re-run this script any time projectGenerator regenerates the .vcxproj." -ForegroundColor Yellow

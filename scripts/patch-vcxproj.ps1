Idempotently apply Nottawa's required MSVC project settings to a .vcxproj
freshly generated by OpenFrameworks projectGenerator.

.DESCRIPTION
projectGenerator produces a serviceable .vcxproj but omits Nottawa-specific
include paths, preprocessor defines, subsystem choice, .mm/.m exclusion,
and the Windows _win.cpp stub inclusion. This script edits the .vcxproj in
place. Safe to re-run after every projectGenerator invocation.

.PARAMETER Project
Path to the .vcxproj to patch. Default: apps/myApps/Nottawa/Nottawa.vcxproj
relative to repo root.

.PARAMETER RepoRoot
Repo root (directory that contains src/). Default: two levels up from this script.

.EXAMPLE
pwsh scripts\patch-vcxproj.ps1
pwsh scripts\patch-vcxproj.ps1 -Project C:\path\to\Nottawa.vcxproj
#>

